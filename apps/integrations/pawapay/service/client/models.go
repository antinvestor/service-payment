// OperationConfig describes the limits and behaviour of one operation type
// for a provider currency in the active configuration.
type OperationConfig struct {
	MinAmount        string `json:"minAmount"`
	MaxAmount        string `json:"maxAmount"`
	DecimalsInAmount string `json:"decimalsInAmount"` // TWO_PLACES or NONE
	Status           string `json:"status"`           // OPERATIONAL, DELAYED or CLOSED
	CallbackURL      string `json:"callbackUrl"`
	AuthType         string `json:"authType"`  // deposits: PROVIDER_AUTH, PREAUTH or REDIRECT_AUTH
	PinPrompt        string `json:"pinPrompt"` // deposits: AUTOMATIC or MANUAL
}

// CurrencyConfig describes a currency supported by a provider in the active configuration.
type CurrencyConfig struct {
	Currency       string                     `json:"currency"`
	DisplayName    string                     `json:"displayName"`
	OperationTypes map[string]OperationConfig `json:"operationTypes"`
}

// ProviderConfig describes a provider configured for the account.
type ProviderConfig struct {
	Provider                string           `json:"provider"`
	DisplayName             string           `json:"displayName"`
	NameDisplayedToCustomer string           `json:"nameDisplayedToCustomer"`
	Currencies              []CurrencyConfig `json:"currencies"`
}

// CountryConfig describes a country configured for the account.
type CountryConfig struct {
	Country   string           `json:"country"`
	Prefix    string           `json:"prefix"`
	Providers []ProviderConfig `json:"providers"`
}

// SignatureConfiguration describes the account's request/callback signing setup.
type SignatureConfiguration struct {
	SignedRequestsOnly bool `json:"signedRequestsOnly"`
	SignedCallbacks    bool `json:"signedCallbacks"`
}

// ActiveConfiguration is the response of the active-conf toolkit endpoint.
type ActiveConfiguration struct {
	CompanyName            string                 `json:"companyName"`
	SignatureConfiguration SignatureConfiguration `json:"signatureConfiguration"`
	Countries              []CountryConfig        `json:"countries"`
}

// OperationAvailability is the status of one operation type for a provider.
type OperationAvailability struct {
	OperationType string `json:"operationType"`
	Status        string `json:"status"` // OPERATIONAL, DELAYED or CLOSED
}

// ProviderAvailability is the availability of a single provider.
type ProviderAvailability struct {
	Provider       string                  `json:"provider"`
	OperationTypes []OperationAvailability `json:"operationTypes"`
}

// CountryAvailability is the availability of all providers in a country.
type CountryAvailability struct {
	Country   string                 `json:"country"`
	Providers []ProviderAvailability `json:"providers"`
}
