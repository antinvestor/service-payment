// PaymentPageRequest creates a hosted Payment Page session.
type PaymentPageRequest struct {
	// DepositID is a UUIDv4 unique ID generated by the caller for reconciliation.
	DepositID string
	// ReturnURL is where the customer is redirected after payment processing.
	ReturnURL string
	// Amount and Currency optionally fix the amount on the page.
	Amount   string
	Currency string
	// PhoneNumber optionally prefills the customer phone number.
	PhoneNumber string
	// Language of the page: EN or FR.
	Language string
	// Country optionally restricts payment to phone numbers of one country.
	Country string
	// Reason is shown to the customer to specify what they are paying for.
	Reason string
	// CustomerMessage is a 4-22 char alphanumeric narration shown to the customer.
	CustomerMessage string
	// Metadata is attached to the payment and echoed back in callbacks.
	Metadata map[string]string
}

